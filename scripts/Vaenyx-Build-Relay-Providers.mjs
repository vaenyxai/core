// Generate runtime-neutral SDK adapters from the same source the local server executes.
import fs from "node:fs";
import path from "node:path";
import ts from "typescript";
const root = path.resolve(import.meta.dirname, ".."),
  folder = path.join(root, "packages/relay-client");
const check = process.argv.includes("--check");
const source = (name) =>
  fs.readFileSync(
    path.join(root, "apps/server/src/modules/core", name),
    "utf8",
  );
const definitions = source("relay-api-config.ts");
const start = definitions.indexOf("export const API_PROVIDERS ="),
  end = definitions.indexOf("] as const;", start) + "] as const;".length;
if (start < 0 || end < start)
  throw Error("Provider definition boundaries changed");
const outputs = {
  "provider-definitions.mjs": definitions.slice(start, end),
  "provider-wire.mjs": source("relay-api-wire.ts"),
  "search.mjs": source("relay-search.ts").replaceAll(
    "new URL(",
    "new globalThis.URL(",
  ),
  "providers.mjs": source("relay-api-provider.ts")
    .replaceAll("./relay-api-config.js", "./provider-definitions.mjs")
    .replaceAll("./relay-api-wire.js", "./provider-wire.mjs"),
};
for (const [name, source] of Object.entries(outputs)) {
  const code =
    "// Generated by Vaenyx-Build-Relay-Providers.mjs. Edit the Core source.\n" +
    ts.transpileModule(source, {
      compilerOptions: {
        target: ts.ScriptTarget.ES2022,
        module: ts.ModuleKind.ESNext,
      },
    }).outputText;
  const file = path.join(folder, name);
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== code)
      throw Error("Generated provider differs: " + name);
  } else fs.writeFileSync(file, code);
}
console.log("Shared provider adapters " + (check ? "verified" : "generated"));
